import 'dart:typed_data';

import 'package:firebase_storage/firebase_storage.dart';
import 'package:mime_type/mime_type.dart';

Future<String?> uploadData(String path, Uint8List data) async {
  final storageRef = FirebaseStorage.instance.ref().child(path);
  final metadata = SettableMetadata(contentType: mime(path));
  final result = await storageRef.putData(data, metadata);
  return result.state == TaskState.success ? result.ref.getDownloadURL() : null;
}

Future<String?> uploadDataAndGetStoragePath(String path, Uint8List data) async {
  final storageRef = FirebaseStorage.instance.ref().child(path);
  final metadata = SettableMetadata(contentType: mime(path));
  final result = await storageRef.putData(data, metadata);
  return result.state == TaskState.success ? result.ref.fullPath : null;
}

Future<void> deleteStorageObject(String storagePath) async {
  final normalizedPath = storagePath.trim();
  if (normalizedPath.isEmpty) {
    return;
  }

  await FirebaseStorage.instance.ref().child(normalizedPath).delete();
}
